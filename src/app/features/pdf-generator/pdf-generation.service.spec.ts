import { TestBed } from '@angular/core/testing';
import { describe, expect, it, vi } from 'vitest';
import { BandStateService } from '../character-sheet/band-state.service';
import { GENERATE_BAND_PDF, PdfGenerationService } from './pdf-generation.service';
import type { GenerateBandPdf } from './pdf-generation.service';
import { PDF_TEMPLATE_OPTIONS, PdfTemplatesService } from './pdf-templates.service';

function setup(generate: GenerateBandPdf, multipleTemplates = false) {
  TestBed.configureTestingModule({ providers: [
    { provide: GENERATE_BAND_PDF, useValue: generate },
    ...(multipleTemplates ? [{ provide: PDF_TEMPLATE_OPTIONS, useValue: [
      { id: 'first', label: 'First', create: () => ({ configUrl: '/first.json', fontUrls: {} }) },
      { id: 'second', label: 'Second', create: () => ({ configUrl: '/second.json', fontUrls: {} }) },
    ] }] : []),
  ] });
  return { pdf: TestBed.inject(PdfGenerationService), state: TestBed.inject(BandStateService), templates: TestBed.inject(PdfTemplatesService) };
}

describe('PDF generation state', () => {
  it('ignores duplicate requests and discards a result if the band changed during generation', async () => {
    let release!: (bytes: Uint8Array) => void;
    const generate = vi.fn<GenerateBandPdf>(() => new Promise((resolve) => { release = resolve; }));
    const { pdf, state } = setup(generate);
    state.setName(0, 'Before');
    const pending = pdf.generate();
    expect(pdf.generating()).toBe(true);
    await pdf.generate();
    expect(generate).toHaveBeenCalledTimes(1);
    state.setName(0, 'After');
    expect(generate.mock.calls[0][0].ninjas[0].name).toBe('Before');
    release(new Uint8Array([1, 2, 3]));
    await pending;
    expect(pdf.getPdfBytes()).toBeNull();
    expect(pdf.status().message).toContain('Your squad changed');
    expect(pdf.generating()).toBe(false);
  });

  it('returns a copy of the generated bytes and invalidates it after edits', async () => {
    const { pdf, state } = setup(async () => new Uint8Array([1, 2, 3]));
    await pdf.generate();
    pdf.getPdfBytes()![0] = 99;
    expect(pdf.getPdfBytes()).toEqual(new Uint8Array([1, 2, 3]));
    state.addEquipment(0, 'items');
    expect(pdf.getPdfBytes()).toBeNull();
    expect(pdf.status().message).toBe('Ready to generate your sheet.');
  });

  it('announces errors, releases the loading state and allows another attempt', async () => {
    const generate = vi.fn<GenerateBandPdf>().mockRejectedValueOnce(new Error('Missing template')).mockResolvedValueOnce(new Uint8Array([1]));
    const { pdf } = setup(generate);
    await pdf.generate();
    expect(pdf.status().phase).toBe('error');
    expect(pdf.status().message).toContain('Missing template');
    expect(pdf.generating()).toBe(false);
    await pdf.generate();
    expect(pdf.status().phase).toBe('success');
  });

  it('passes the selected template to the generator without changing the band', async () => {
    const generate = vi.fn<GenerateBandPdf>().mockResolvedValue(new Uint8Array([1]));
    const { pdf, state, templates } = setup(generate, true);
    state.setBandName('Cuervos');
    const band = state.band();
    templates.select('second');
    await pdf.generate();
    expect(generate).toHaveBeenCalledWith(band, { configUrl: '/second.json', fontUrls: {} });
    expect(state.band()).toBe(band);
    expect(pdf.hasPdf()).toBe(true);
    templates.select('first');
    expect(pdf.hasPdf()).toBe(false);
    templates.select('second');
    expect(pdf.getPdfBytes()).toBeNull();
    await pdf.generate();
    expect(pdf.hasPdf()).toBe(true);
  });

  it('discards pending results when the template changes, even if the original is selected again', async () => {
    let release!: (bytes: Uint8Array) => void;
    const { pdf, templates } = setup(() => new Promise((resolve) => { release = resolve; }), true);
    const pending = pdf.generate();
    templates.select('second');
    templates.select('first');
    expect(pdf.hasPdf()).toBe(false);
    release(new Uint8Array([1]));
    await pending;
    expect(pdf.hasPdf()).toBe(false);
    expect(pdf.generating()).toBe(false);
    expect(pdf.status().message).toContain('different template');
  });

  it('discards an error from a generation superseded by an edit', async () => {
    let fail!: (reason: Error) => void;
    const { pdf, state } = setup(() => new Promise((_, reject) => { fail = reject; }));
    const pending = pdf.generate();
    state.setBandName('New name');
    fail(new Error('Old generation failed'));
    await pending;
    expect(pdf.status().phase).toBe('idle');
    expect(pdf.status().message).not.toContain('Old generation failed');
  });
});
