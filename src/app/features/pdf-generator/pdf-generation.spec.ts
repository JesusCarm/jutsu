import { TestBed } from '@angular/core/testing';
import { describe, expect, it, vi } from 'vitest';
import { BandState } from '../character-sheet/band-state';
import { GENERATE_BAND_PDF, PdfGeneration } from './pdf-generation';
import type { GenerateBandPdf } from './pdf-generation';

function setup(generate: GenerateBandPdf) {
  TestBed.configureTestingModule({ providers: [{ provide: GENERATE_BAND_PDF, useValue: generate }] });
  return { pdf: TestBed.inject(PdfGeneration), state: TestBed.inject(BandState) };
}

describe('PDF generation state', () => {
  it('ignores duplicate requests and discards a result if the band changed during generation', async () => {
    let release!: (bytes: Uint8Array) => void;
    const generate = vi.fn<GenerateBandPdf>(() => new Promise((resolve) => { release = resolve; }));
    const { pdf, state } = setup(generate);
    state.setName(0, 'Before');
    const pending = pdf.generate();
    expect(pdf.generating()).toBe(true);
    await pdf.generate();
    expect(generate).toHaveBeenCalledTimes(1);
    state.setName(0, 'After');
    expect(generate.mock.calls[0][0].ninjas[0].name).toBe('Before');
    release(new Uint8Array([1, 2, 3]));
    await pending;
    expect(pdf.getPdfBytes()).toBeNull();
    expect(pdf.status().message).toContain('Your squad changed');
    expect(pdf.generating()).toBe(false);
  });

  it('returns a copy of the generated bytes and invalidates it after edits', async () => {
    const { pdf, state } = setup(async () => new Uint8Array([1, 2, 3]));
    await pdf.generate();
    pdf.getPdfBytes()![0] = 99;
    expect(pdf.getPdfBytes()).toEqual(new Uint8Array([1, 2, 3]));
    state.addEquipment(0, 'items');
    expect(pdf.getPdfBytes()).toBeNull();
    expect(pdf.status().message).toBe('Ready to generate your sheet.');
  });

  it('announces errors, releases the loading state and allows another attempt', async () => {
    const generate = vi.fn<GenerateBandPdf>().mockRejectedValueOnce(new Error('Missing template')).mockResolvedValueOnce(new Uint8Array([1]));
    const { pdf } = setup(generate);
    await pdf.generate();
    expect(pdf.status().phase).toBe('error');
    expect(pdf.status().message).toContain('Missing template');
    expect(pdf.generating()).toBe(false);
    await pdf.generate();
    expect(pdf.status().phase).toBe('success');
  });
});
